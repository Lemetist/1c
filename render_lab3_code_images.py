def main() -> None:
    OUTPUT_DIR.mkdir(exist_ok=True)
    font = ImageFont.truetype(FONT_PATH, FONT_SIZE)

    for name, text in SNIPPETS.items():
        lines = text.splitlines() or [""]
        width = max(int(font.getlength(line)) for line in lines) + PADDING_X * 2
        line_height = font.getbbox("Ag")[3] - font.getbbox("Ag")[1]
        text_height = len(lines) * line_height + (len(lines) - 1) * LINE_SPACING
        height = text_height + PADDING_Y * 2 + WINDOW_BAR_HEIGHT

        image = Image.new("RGB", (width, height), "#f5f5f5")
        draw = ImageDraw.Draw(image)

        draw.rounded_rectangle((0, 0, width - 1, height - 1), radius=14, fill="#f5f5f5", outline="#bdbdbd", width=2)
        draw.rounded_rectangle((0, 0, width - 1, WINDOW_BAR_HEIGHT + 10), radius=14, fill="#e8e8e8", outline="#e8e8e8")
        draw.ellipse((18, 11, 30, 23), fill="#ff5f57")
        draw.ellipse((38, 11, 50, 23), fill="#febc2e")
        draw.ellipse((58, 11, 70, 23), fill="#28c840")

        y = PADDING_Y + WINDOW_BAR_HEIGHT
        for line in lines:
            draw.text((PADDING_X, y), line, font=font, fill="#202124")
            y += line_height + LINE_SPACING

        image.save(OUTPUT_DIR / name)


if __name__ == "__main__":
    main()
