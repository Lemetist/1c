def wrap_line(line: str, width: int) -> list[str]:
    if not line:
        return [""]
    indent_len = len(line) - len(line.lstrip(" "))
    indent = line[:indent_len]
    content = line[indent_len:]
    if len(line) <= width:
        return [line]
    wrapped = textwrap.wrap(
        content,
        width=max(width - indent_len, 8),
        break_long_words=True,
        break_on_hyphens=False,
        replace_whitespace=False,
        drop_whitespace=False,
    )
    result = []
    for idx, part in enumerate(wrapped):
        result.append((indent if idx == 0 else indent) + part)
    return result


def wrap_text(text: str, width: int) -> str:
    lines = []
    for raw_line in text.splitlines():
        lines.extend(wrap_line(raw_line, width))
    return "\n".join(lines)


def render_terminal_image(name: str, text: str, width_chars: int) -> Path:
    IMG_DIR.mkdir(exist_ok=True)
    wrapped = wrap_text(text, width_chars)
    lines = wrapped.splitlines() or [""]
    font = ImageFont.truetype(FONT_PATH, FONT_SIZE)
    sample_bbox = font.getbbox("Ag")
    line_height = sample_bbox[3] - sample_bbox[1]
    longest = max(len(line) for line in lines)
    img_w = PAD_X * 2 + max(1, longest) * int(font.getlength("0"))
    img_h = PAD_Y * 2 + len(lines) * line_height + max(0, len(lines) - 1) * LINE_GAP
    image = Image.new("RGB", (img_w, img_h), BG)
    draw = ImageDraw.Draw(image)
    y = PAD_Y
    for line in lines:
        draw.text((PAD_X, y), line, font=font, fill=FG)
        y += line_height + LINE_GAP
    path = IMG_DIR / f"{name}.png"
    image.save(path)
    return path


def image_tag(path: Path, alt: str) -> str:
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return (
        f'<img alt="{html.escape(alt)}" '
        f'src="data:image/png;base64,{data}">'
    )


